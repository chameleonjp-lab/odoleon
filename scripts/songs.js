// Real-time Web Audio DSP Beat & Onset Analyzer -> Generates exact 240 beat-synced notes from ANY loaded WAV/MP3!
export function analyzeAudioAndBuildChart(audioBuffer, targetCount = 240) {
  const sr = audioBuffer.sampleRate;
  const dur = audioBuffer.duration;
  const ch0 = audioBuffer.getChannelData(0);
  const ch1 = audioBuffer.numberOfChannels > 1 ? audioBuffer.getChannelData(1) : ch0;

  // 1) Compute 10ms RMS energy & positive onset flux envelope
  const hop = Math.max(1, Math.floor(sr * 0.01));
  const frames = Math.floor(ch0.length / hop);
  const flux = new Float32Array(frames);
  let prevE = 0;
  for (let f = 0; f < frames; f++) {
    let sum = 0;
    const start = f * hop;
    const end = Math.min(ch0.length, start + hop);
    for (let i = start; i < end; i += 2) {
      const s = (ch0[i] + ch1[i]) * 0.5;
      sum += s * s;
    }
    const rms = Math.sqrt(sum / Math.max(1, (end - start) / 2));
    flux[f] = Math.max(0, rms - prevE);
    prevE = rms * 0.72 + prevE * 0.28;
  }

  // 2) Estimate BPM (92..164 BPM) via onset autocorrelation
  let bestLag = 47; // ~127.6 BPM default
  let bestCorr = -1;
  const minLag = Math.floor(60 / 164 / 0.01); // 36
  const maxLag = Math.ceil(60 / 92 / 0.01);   // 66
  const sampleFrames = Math.min(frames, 6000); // first 60s enough for rock-solid BPM
  for (let lag = minLag; lag <= maxLag; lag++) {
    let corr = 0;
    for (let f = 0; f < sampleFrames - lag; f += 2) {
      corr += flux[f] * flux[f + lag];
    }
    if (corr > bestCorr) {
      bestCorr = corr;
      bestLag = lag;
    }
  }
  const detectedBpm = Math.round(60 / (bestLag * 0.01));
  const beatSec = 60 / detectedBpm;
  const eighthSec = beatSec / 2;

  // 3) Find best downbeat phase alignment (0 .. beatSec)
  let bestPhase = 0;
  let bestPhaseScore = -1;
  for (let p = 0; p < bestLag; p++) {
    let sc = 0;
    for (let f = p; f < sampleFrames; f += bestLag) sc += flux[f];
    if (sc > bestPhaseScore) {
      bestPhaseScore = sc;
      bestPhase = p * 0.01;
    }
  }

  // 4) Score every 8th-note grid slot across the song by real local onset energy + downbeat preference
  const candidates = [];
  const startT = Math.max(1.8, bestPhase + beatSec * 2);
  const endT = Math.max(startT + 10, dur - 2.6);
  let gridIdx = 0;
  for (let t = startT; t <= endT; t += eighthSec) {
    const cf = Math.round(t / 0.01);
    let peak = 0;
    for (let d = -3; d <= 3; d++) {
      const idx = cf + d;
      if (idx >= 0 && idx < frames && flux[idx] > peak) peak = flux[idx];
    }
    const isDownbeat = gridIdx % 2 === 0;
    const isBar = gridIdx % 8 === 0;
    const score = peak * (isBar ? 1.45 : (isDownbeat ? 1.25 : 0.92)) + (isDownbeat ? 0.002 : 0);
    candidates.push({ time: Number(t.toFixed(3)), score, isOffbeat: !isDownbeat });
    gridIdx++;
  }

  // 5) Select the exact (targetCount - 1) strongest musical beats with clean minimum spacing
  const minGap = Math.max(0.22, eighthSec * 0.92);
  const ranked = [...candidates].sort((a, b) => b.score - a.score);
  const picked = [];
  for (const c of ranked) {
    if (picked.length >= targetCount - 1) break;
    if (picked.every((p) => Math.abs(p.time - c.time) >= minGap)) {
      picked.push(c);
    }
  }
  picked.sort((a, b) => a.time - b.time);

  // 6) Assign fun dance choreography moves (1..6) + climactic 240th Finale note!
  const moveSeq = [1, 2, 3, 4, 5, 2, 3, 4, 1, 5, 3, 6];
  const chart = picked.map((p, i) => ({
    time: p.time,
    move: moveSeq[i % moveSeq.length],
    cue: i === 0 ? 'ミュージック スタート！' : (i === Math.floor(targetCount * 0.5) ? '折り返し！ノリノリ！' : ''),
    isFinale: false,
    isOffbeat: p.isOffbeat
  }));
  const lastT = Math.min(dur - 1.2, (chart.length ? chart[chart.length - 1].time + beatSec : dur - 2.0));
  chart.push({
    time: Number(lastT.toFixed(3)),
    move: 6,
    cue: 'ラスト！決めるよ！',
    isFinale: true,
    isOffbeat: false
  });

  return { bpm: detectedBpm, duration: dur, chart };
}

